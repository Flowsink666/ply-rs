"""Structural contracts implemented by either runtime backend."""

from typing import Any, List, Protocol

from rply.core.parser_context import ParseContext
from rply.core.lexer_config import LexerSnapshot


class LexerRuntime(Protocol):
    pos: int
    lineno: int
    current_state: str
    state_stack: List[str]
    input_revision: int

    @property
    def data(self) -> str: ...

    @property
    def length(self) -> int: ...

    def input(self, text: str) -> None: ...
    def restore_state(self, state: LexerSnapshot) -> None: ...
    def begin(self, state: str) -> None: ...
    def push_state(self, state: str) -> None: ...
    def pop_state(self) -> None: ...
    def skip(self, n: int = 1) -> None: ...
    def token(self) -> Any: ...


class ParserRuntime(Protocol):
    def parse(self, token_stream: Any, *, context: ParseContext) -> Any: ...
